const BY_NAME = new Map<string, ExerciseVisualInfo>(
  EXERCISE_CATALOG.map((item) => [item.name.toLowerCase(), item])
);

/**
 * Finds exact catalog info or intelligently infers muscles, equipment, and visual guide
 * for custom exercises added by the user!
 */
export function getExerciseVisualInfo(
  name: string,
  fallbackCategory: string = 'Pecho',
  fallbackMode: ExerciseMode = 'strength'
): ExerciseVisualInfo {
  const clean = (name || '').trim().toLowerCase();
  const exact = BY_NAME.get(clean);
  if (exact) return exact;

  // Infer from keywords + category
  let equipment: EquipmentType = 'Máquina';
  if (/mancuerna|dumbbell|kettlebell|pesa rusa/.test(clean)) equipment = 'Mancuernas';
  else if (/polea|cable|cuerda|cruce/.test(clean)) equipment = 'Polea';
  else if (/barra|ol[ií]mpica|romano|t-bar/.test(clean)) equipment = 'Barra';
  else if (/plancha|flexi|dominada|fondo|burpee|corporal/.test(clean)) equipment = 'Peso Corporal';
  else if (/bici|cinta|trote|correr|el[ií]ptica|remo erg|cardio|caminata/.test(clean)) equipment = 'Cardio / Bici';

  const cat = (fallbackCategory as CategoryName) || 'Pecho';
  const catDefaults: Record<string, { p: MuscleZone[]; s: MuscleZone[]; refImg: string }> = {
    'Cardio y Bici': { p: ['cardio_heart', 'quads'], s: ['calves', 'glutes'], refImg: 'Bicycling_Stationary' },
    Pecho: { p: ['chest'], s: ['front_delts', 'triceps'], refImg: 'Machine_Bench_Press' },
    Espalda: { p: ['lats', 'mid_back'], s: ['biceps', 'rear_delts'], refImg: 'Wide-Grip_Lat_Pulldown' },
    'Piernas y Glúteos': { p: ['quads', 'glutes'], s: ['hamstrings', 'calves'], refImg: 'Leg_Press' },
    Hombros: { p: ['front_delts', 'side_delts'], s: ['triceps', 'traps'], refImg: 'Seated_Dumbbell_Press' },
    'Bíceps y Tríceps': {
      p: /tr[ií]ceps|extensi|franc[eé]s|patada/.test(clean) ? ['triceps'] : ['biceps'],
      s: ['forearms'],
      refImg: /tr[ií]ceps|extensi|franc[eé]s/.test(clean) ? 'Triceps_Pushdown_-_Rope_Attachment' : 'Dumbbell_Alternate_Bicep_Curl',
    },
    'Abdomen y Tiempo': { p: ['abs', 'obliques'], s: ['glutes'], refImg: 'Plank' },
  };

  const def = catDefaults[cat] || catDefaults['Pecho'];
  return {
    name: name || 'Ejercicio personalizado',
    category: cat,
    mode: fallbackMode,
    equipment,
    primaryMuscles: def.p,
    secondaryMuscles: def.s,
    images: [],
    detectionHint: `Ejercicio personalizado de ${cat}. Los músculos indicados son una estimación por categoría. Agrega tus propias fotos para identificarlo.`,
    cues: [
      'No hay instrucciones específicas verificadas para este ejercicio personalizado.',
      'Consulta la técnica con un profesional y utiliza tus notas para recordar los ajustes.',
      'Puedes guardar fotos de tu equipo para identificarlo sin conexión.',
    ],
  };
}
