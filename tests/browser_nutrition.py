"""Flujos reales de nutrición y peso. Ejecutar con Vite activo: python tests/browser_nutrition.py."""
from playwright.sync_api import sync_playwright, expect
import json
import os

BASE_URL = os.environ.get('BITACORA_URL', 'http://localhost:5173')

with sync_playwright() as p:
    browser = p.chromium.launch(executable_path='/usr/bin/chromium', headless=True, args=['--no-sandbox'])
    context = browser.new_context(viewport={'width': 390, 'height': 844})
    page = context.new_page()
    errors = []
    page.on('pageerror', lambda e: errors.append(str(e)))
    page.on('console', lambda m: errors.append(m.text) if m.type == 'error' else None)
    page.on('dialog', lambda dialog: dialog.accept())
    page.goto(BASE_URL)
    page.get_by_role('button', name='Alimentación', exact=True).click()
    global_date = page.get_by_label('Fecha de los registros')
    global_date.fill('2026-10-31')
    page.locator('#meal-description').fill('Pollo, arroz y ensalada de prueba')
    page.locator('#mealKcal').fill('-1')
    page.locator('#mealProt').fill('31.2')
    page.get_by_role('button', name='+ GUARDAR COMIDA DEL DÍA', exact=True).click()
    expect(page.locator('#mealKcal-error')).to_contain_text('entre 0 y')
    page.locator('#mealKcal').fill('520.5')
    page.locator('#mealCarbs').fill('60.4')
    page.locator('#mealFat').fill('10.1')
    page.locator('#meal-time').fill('13:15')
    page.get_by_role('button', name='Guardar como comida frecuente', exact=True).click()
    expect(page.get_by_text('Tus comidas frecuentes', exact=True)).to_be_visible()
    page.get_by_role('button', name='+ GUARDAR COMIDA DEL DÍA', exact=True).click()
    expect(page.locator('.ticket-row.meal')).to_have_count(1)
    expect(page.locator('.ticket-row.meal')).to_contain_text('520.5 kcal')
    expect(page.locator('.ticket-row.meal')).to_contain_text('60.4g C')
    page.get_by_role('button', name='Editar comida', exact=True).click()
    expect(page.locator('#meal-date')).to_have_value('2026-10-31')
    expect(page.locator('#meal-time')).to_have_value('13:15')
    page.locator('#mealCarbs').fill('62.5')
    page.get_by_role('button', name='ACTUALIZAR COMIDA', exact=True).click()
    expect(page.locator('.ticket-row.meal')).to_contain_text('62.5g C')
    expect(page.locator('.ticket-row.meal')).to_contain_text('13:15')
    assert 'COMIDAS DE HOY' not in page.locator('body').inner_text()
    page.get_by_role('button', name='+200 ml Vaso chico', exact=True).click()
    expect(page.locator('.ticket-row.water')).to_have_count(1)
    page.get_by_role('button', name='Editar ml', exact=True).click()
    page.locator('#custom-water').fill('1.5')
    page.get_by_role('button', name='Actualizar', exact=True).click()
    expect(page.locator('#water-error')).to_contain_text('entera')
    page.locator('#custom-water').fill('350')
    page.locator('#water-date').fill('2026-10-30')
    page.locator('#water-time').fill('08:45')
    page.get_by_role('button', name='Actualizar', exact=True).click()
    expect(page.locator('.ticket-row.water')).to_have_count(0)
    global_date.fill('2026-10-30')
    expect(page.locator('.ticket-row.water')).to_contain_text('350 ml')
    expect(page.locator('.ticket-row.water')).to_contain_text('08:45')
    page.get_by_role('button', name='Progreso', exact=True).click()
    page.locator('#body-weight').fill('80')
    page.locator('#body-fat').fill('-2')
    page.get_by_role('button', name='+ GUARDAR PESO (2026-10-30)', exact=True).click()
    expect(page.locator('#bodyFat-error')).to_contain_text('entre 1 y 75')
    page.locator('#body-fat').fill('18')
    page.locator('#body-waist').fill('84.5')
    page.locator('#metric-date').fill('2026-10-29')
    page.locator('#metric-time').fill('07:30')
    page.locator('#body-notes').fill('Pesaje de prueba')
    page.get_by_role('button', name='+ GUARDAR PESO (2026-10-29)', exact=True).click()
    expect(page.locator('.ticket-row.weight')).to_have_count(1)
    page.get_by_role('button', name='Editar pesaje del 2026-10-29', exact=True).click()
    expect(page.locator('#metric-date')).to_have_value('2026-10-29')
    expect(page.locator('#metric-time')).to_have_value('07:30')
    page.locator('#body-weight').fill('79.8')
    page.get_by_role('button', name='ACTUALIZAR PESAJE', exact=True).click()
    expect(page.locator('.ticket-row.weight')).to_contain_text('79.8 kg')
    expect(page.locator('.ticket-row.weight')).to_contain_text('2026-10-29 • 07:30')
    page.locator('#body-weight').fill('82')
    page.locator('#metric-date').fill('2026-10-01')
    page.get_by_role('button', name='+ GUARDAR PESO (2026-10-01)', exact=True).click()
    expect(page.locator('svg[aria-label="Gráfico de evolución en kg"] [role=button]')).to_have_count(2)
    page.get_by_text('Ver valores del gráfico', exact=True).click()
    expect(page.locator('.chart-values')).to_contain_text('2026-10-29: 79.8 kg')
    page.reload()
    page.get_by_role('button', name='Progreso', exact=True).click()
    expect(page.locator('.ticket-row.weight')).to_have_count(2)
    page.get_by_role('button', name='Eliminar pesaje del 2026-10-01', exact=True).click()
    expect(page.locator('.ticket-row.weight')).to_have_count(1)
    page.get_by_role('button', name='Alimentación', exact=True).click()
    global_date.fill('2026-10-31')
    expect(page.locator('.ticket-row.meal')).to_have_count(1)
    page.get_by_role('button', name='Eliminar comida', exact=True).click()
    expect(page.locator('.ticket-row.meal')).to_have_count(0)
    global_date.fill('2026-10-30')
    page.get_by_role('button', name='Eliminar toma', exact=True).click()
    expect(page.locator('.ticket-row.water')).to_have_count(0)
    page.get_by_role('button', name='CALCULAR POR GRAMOS', exact=False).click()
    page.locator('#food-selector').select_option('pollo_cocido')
    page.locator('#food-amount').fill('200')
    page.get_by_role('button', name='+ Sumar al plato', exact=True).click()
    expect(page.locator('#mealKcal')).to_have_value('330')
    expect(page.locator('#mealProt')).to_have_value('62')
    page.locator('#food-amount').fill('-10')
    page.get_by_role('button', name='+ Sumar al plato', exact=True).click()
    expect(page.locator('#amount-error')).to_be_visible()
    for width in (320, 360, 390, 412, 768, 1280):
        page.set_viewport_size({'width': width, 'height': 900})
        assert page.evaluate('document.documentElement.scrollWidth <= innerWidth'), f'Desbordamiento a {width}px'
    assert not errors, errors
    print(json.dumps({'resultado': 'correcto', 'flujos': ['validación de nutrientes y agua', 'comida frecuente', 'guardar y editar macros', 'corregir fecha y hora', 'pesajes reales y gráfica', 'persistencia tras recarga', 'eliminar con confirmación', 'calculadora por gramos'], 'anchos_sin_desbordamiento': [320, 360, 390, 412, 768, 1280], 'errores_consola': errors}, ensure_ascii=False))
    context.close()
    browser.close()
